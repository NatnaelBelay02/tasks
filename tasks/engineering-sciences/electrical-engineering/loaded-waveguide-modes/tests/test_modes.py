"""Verifier for loaded-waveguide-modes.

The submitted program /root/results/modes.py is run once on each held-out guide file in /tests/data
(four runs, all at once), as an unprivileged user (uid/gid 65534) in its own writable working
directory, with the guide file in a read-only input directory.  Its output is parsed as data, never
executed, and graded against the certified modes of those guides (heldout_truth.json of each run,
generated by /tests/truth_generator/make_truth.py from heldout_guides.json).  Values are compared as
gamma = alpha + j beta; the per-layer power fractions of each matched mode are compared component by
component.  The tests map to the numbered requirements of instruction.md; every test must pass for
reward 1.
"""
import json
import math
import hashlib
import os
import re
import shutil
import signal
import stat
import subprocess
import sys
import tempfile
import time

import pytest

PROGRAM = '/root/results/modes.py'
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')
RUNS = sorted(d for d in os.listdir(DATA) if d.startswith('run_'))
WALL_SEC = 3600                 # per run; all runs are concurrent
MAX_PROGRAM_BYTES = 50_000_000
MAX_BYTES = 16 * 1024 * 1024
MAX_FAMILIES = 400
MAX_LIST = 1000
SANDBOX_UID = SANDBOX_GID = 65534
SANDBOX_ENV = {'HOME': '/tmp', 'PATH': '/usr/local/bin:/usr/bin:/bin', 'LANG': 'C.UTF-8',
               'OPENBLAS_NUM_THREADS': '1', 'OMP_NUM_THREADS': '1', 'MKL_NUM_THREADS': '1',
               'NUMEXPR_NUM_THREADS': '1'}
KEYS = {'modes'}
DIRS = {'forward', 'reverse'}
FAMILY = re.compile(r'LSE(0|[1-9][0-9]*)|LSM[1-9][0-9]*|HYB[1-9][0-9]*')   # used with fullmatch

TOL_GAMMA = 1e-7          # |gamma - gamma*| <= TOL_GAMMA |gamma*|, gamma = alpha + j beta
TOL_POWER = 1e-6          # |p_i - p_i*| <= TOL_POWER sum_k |p_k*| for every layer i


def _load(run, name):
    with open(os.path.join(DATA, run, name)) as fh:
        return json.load(fh)


GUIDES = {r: _load(r, 'heldout_guides.json')['guides'] for r in RUNS}
TRUTH = {r: _load(r, 'heldout_truth.json') for r in RUNS}


# --------------------------------------------------------------- sandboxed execution ---

def _demote():
    os.setsid()
    os.setgroups([])
    os.setgid(SANDBOX_GID)
    os.setuid(SANDBOX_UID)


def _sandbox_pids():
    pids = []
    for pid in os.listdir('/proc'):
        if not pid.isdigit():
            continue
        try:
            with open('/proc/%s/status' % pid) as fh:
                uid = next(line for line in fh if line.startswith('Uid:')).split()[1]
        except (OSError, StopIteration):
            continue
        if int(uid) == SANDBOX_UID:
            pids.append(int(pid))
    return pids


def _kill_sandbox_user():
    """Kill every process owned by the sandbox uid (background children included): a helper that has
    become the sandbox user calls kill(-1, SIGKILL), repeated until none is left."""
    for _ in range(200):
        if not _sandbox_pids():
            return
        pid = os.fork()
        if pid == 0:
            try:
                os.setgroups([])
                os.setgid(SANDBOX_GID)
                os.setuid(SANDBOX_UID)
                os.kill(-1, signal.SIGKILL)
            finally:
                os._exit(0)
        os.waitpid(pid, 0)
        time.sleep(0.05)
    raise RuntimeError('processes of the sandbox user survived repeated kill(-1, SIGKILL)')


def _read_regular(path, limit):
    """Bytes of a regular file, without following a symlink and without blocking (a FIFO or device is
    rejected by the type check); None if absent, not regular, or larger than limit."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC)
    except OSError:
        return None
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode) or st.st_size > limit:
            return None
        chunks, size = [], 0
        while size <= limit:
            b = os.read(fd, min(1 << 20, limit + 1 - size))
            if not b:
                break
            chunks.append(b)
            size += len(b)
        return None if size > limit else b''.join(chunks)
    finally:
        os.close(fd)


def _stage(program, run, root):
    """Fresh run directory: a read-only input directory with guides.json, and a writable working
    directory holding only a copy of the program."""
    base = tempfile.mkdtemp(prefix='run_', dir=root)
    os.chmod(base, 0o755)
    # a name the program cannot know in advance: derived from the private temporary directory
    data_dir = os.path.join(base, 'input_' + hashlib.sha256((base + run).encode()).hexdigest()[:8])
    os.mkdir(data_dir)
    shutil.copyfile(os.path.join(DATA, run, 'heldout_guides.json'), os.path.join(data_dir, 'guides.json'))
    os.chmod(os.path.join(data_dir, 'guides.json'), 0o444)
    os.chmod(data_dir, 0o555)
    work = os.path.join(base, 'work')
    os.mkdir(work)
    os.chmod(work, 0o1777)
    with open(os.path.join(work, 'modes.py'), 'wb') as fh:
        fh.write(program)
    os.chmod(os.path.join(work, 'modes.py'), 0o444)
    return data_dir, work


def _check_sandbox(data_dir, work):
    """The stated execution contract holds for the sandbox user: the working directory and /tmp are
    writable, the input directory is not, and /tests is unreadable."""
    probe = ("import os,sys\n"
             "open('probe.txt','w').write('x'); os.remove('probe.txt')\n"
             "p='/tmp/probe_%d' % os.getpid(); open(p,'w').write('x'); os.remove(p)\n"
             "d=sys.argv[1]\n"
             "assert open(os.path.join(d,'guides.json')).read(1)\n"
             "try:\n    open(os.path.join(d,'w.txt'),'w'); sys.exit('input directory writable')\n"
             "except PermissionError:\n    pass\n"
             "try:\n    os.listdir('/tests'); sys.exit('/tests readable')\n"
             "except PermissionError:\n    pass\n")
    r = subprocess.run([sys.executable, '-c', probe, data_dir], cwd=work, env=SANDBOX_ENV, preexec_fn=_demote,
                       stdin=subprocess.DEVNULL, capture_output=True, timeout=60)
    assert r.returncode == 0, 'sandbox self-check failed: %s' % r.stderr.decode(errors='replace')[-500:]


# --------------------------------------------------------------- parsing the output ---

def _reject_constant(name):
    raise ValueError('non-finite JSON constant %s' % name)


def _unique_keys(pairs):
    keys = [k for k, _ in pairs]
    if len(set(keys)) != len(keys):
        raise ValueError('repeated key in a JSON object')
    return dict(pairs)


def _is_number(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def _mode_ok(p, nlayers):
    return (isinstance(p, list) and len(p) == 3 and _is_number(p[0]) and _is_number(p[1]) and p[1] > 0
            and isinstance(p[2], list) and len(p[2]) == nlayers and all(_is_number(x) for x in p[2]))


def _check_family_map(obj, what, nlayers):
    assert isinstance(obj, dict) and len(obj) <= MAX_FAMILIES, \
        '%s must be an object with at most %d families' % (what, MAX_FAMILIES)
    for fam, lst in obj.items():
        assert isinstance(fam, str) and FAMILY.fullmatch(fam), '%s: %r is not a family name' % (what, fam)
        assert isinstance(lst, list) and 1 <= len(lst) <= MAX_LIST and all(_mode_ok(x, nlayers) for x in lst), \
            ('%s[%s] must be a non-empty list of at most %d [beta, alpha, power] entries: finite numbers, alpha > 0, '
             'power a list of %d finite numbers (one per layer)') % (what, fam, MAX_LIST, nlayers)


def _check_contract(out, guides):
    """Raise AssertionError naming the first field that breaks the format."""
    assert isinstance(out, dict) and set(out) == {'guides'}, 'top level must be {"guides": ...}'
    res = out['guides']
    assert isinstance(res, dict), '"guides" must be an object'
    ids = {g['id'] for g in guides}
    assert set(res) == ids, 'guide ids differ from the input: missing %s, extra %s' % (
        sorted(ids - set(res)), sorted(set(res) - ids))
    for g in guides:
        gid = g['id']
        r = res[gid]
        assert isinstance(r, dict) and set(r) == KEYS, '%s: keys must be exactly %s' % (gid, sorted(KEYS))
        m = r['modes']
        assert isinstance(m, list) and len(m) == len(g['test_frequencies']), \
            '%s: modes must have one entry per test frequency' % gid
        for j, item in enumerate(m):
            assert isinstance(item, dict) and set(item) == DIRS, \
                '%s modes[%d] must be an object with exactly the keys forward and reverse' % (gid, j)
            for dr in ('forward', 'reverse'):
                _check_family_map(item[dr], '%s modes[%d].%s' % (gid, j, dr), len(g['layers']))


def _parse(raw, guides):
    out = json.loads(raw.decode('utf-8'), parse_constant=_reject_constant, object_pairs_hook=_unique_keys)
    _check_contract(out, guides)
    return out['guides']


# --------------------------------------------------------------- the runs ---

@pytest.fixture(scope='session')
def runs():
    """Run the submitted program once on every held-out guide file (concurrently) and collect the raw
    outputs: {run: {'error': str} or {'returncode', 'elapsed', 'raw'}}."""
    program = _read_regular(PROGRAM, MAX_PROGRAM_BYTES)
    if program is None:
        return {r: {'error': '%s is missing, not a regular file, a symlink, or larger than %d bytes' % (PROGRAM, MAX_PROGRAM_BYTES)}
                for r in RUNS}
    root = tempfile.mkdtemp(prefix='wgm_')
    os.chmod(root, 0o755)
    procs = {}
    for run in sorted(RUNS):                     # fixed launch order: the verdict does not depend on chance
        data_dir, work = _stage(program, run, root)
        _check_sandbox(data_dir, work)
        out = os.path.join(work, 'modes.json')
        log = tempfile.TemporaryFile()                  # unlinked file, not a pipe
        p = subprocess.Popen([sys.executable, 'modes.py', os.path.join(data_dir, 'guides.json'), out], cwd=work,
                             env=SANDBOX_ENV, preexec_fn=_demote, stdin=subprocess.DEVNULL, stdout=log, stderr=log)
        procs[run] = (p, out, log, time.monotonic())
    results = {}
    for run, (p, out, log, t0) in procs.items():
        try:
            rc = p.wait(timeout=max(1.0, t0 + WALL_SEC - time.monotonic()))
            results[run] = {'returncode': rc, 'elapsed': time.monotonic() - t0}
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)
            p.wait()
            results[run] = {'error': 'program did not finish within %d s' % WALL_SEC}
    _kill_sandbox_user()
    for run, (p, out, log, t0) in procs.items():
        log.seek(0, os.SEEK_END)
        log.seek(max(0, log.tell() - 2000))
        tail = log.read().decode(errors='replace')
        log.close()
        r = results[run]
        print('%s: %s; output tail:\n%s' % (run, r, tail))
        if 'error' in r:
            continue
        if r['returncode'] != 0:
            r['error'] = 'program exited with status %d; last output:\n%s' % (r['returncode'], tail[-1000:])
            continue
        raw = _read_regular(out, MAX_BYTES)
        if raw is None:
            r['error'] = 'modes.json is missing, not a regular file, a symlink, or larger than 16 MiB'
            continue
        r['raw'] = raw
    shutil.rmtree(root, ignore_errors=True)
    return results


def _output(runs, run):
    r = runs[run]
    assert 'error' not in r, '%s: %s' % (run, r['error'])
    try:
        return _parse(r['raw'], GUIDES[run])
    except (ValueError, UnicodeDecodeError) as e:
        raise AssertionError('%s: modes.json is not valid JSON under the stated rules: %s' % (run, e))


def _match(rep, ref):
    """Pair reported and true gamma values one-to-one within the tolerance.  The true values of one
    family are at least 1e-4 |gamma| apart (instruction), a thousand times the tolerance, so a
    reported value lies within the tolerance of at most one true value.  Returns the true values
    left unmatched, the reported values left unmatched, and the matched (reported, true) entries."""
    left = list(rep)
    miss, pairs = [], []
    for r in ref:
        g = complex(float(r[1]), float(r[0]))
        k = next((i for i, x in enumerate(left) if abs(complex(x[1], x[0]) - g) <= TOL_GAMMA * abs(g)), None)
        if k is None:
            miss.append(g)
        else:
            pairs.append((left.pop(k), r))
    return miss, [complex(x[1], x[0]) for x in left], pairs


def _entries(output, run):
    """(label, reported family map, true family map) for every guide, test frequency and direction."""
    for g in GUIDES[run]:
        gid = g['id']
        for j, (rep, ref) in enumerate(zip(output[gid]['modes'], TRUTH[run][gid]['modes'])):
            for dr in ('forward', 'reverse'):
                yield '%s at %s Hz, %s' % (gid, g['test_frequencies'][j], dr), rep[dr], ref[dr]


@pytest.mark.parametrize('run', RUNS)
def test_run_completes(runs, run):
    """Requirement 1: on this held-out guide file the program exits with status 0 within the wall-clock
    limit and leaves modes.json as a regular file (not a symlink) of at most 16 MiB."""
    r = runs[run]
    assert 'error' not in r, '%s: %s' % (run, r['error'])


@pytest.mark.parametrize('run', RUNS)
def test_output_contract(runs, run):
    """Requirement 2: modes.json is UTF-8 JSON with no key repeated in any object and no NaN or
    Infinity, and has exactly the required structure: every guide id of the input and no other, exactly
    the key modes, one entry per test frequency with exactly the keys forward and reverse, family names
    exactly LSE<n> (n >= 0), LSM<n> or HYB<n> (n >= 1) without leading zeros, at most 400 families per
    map, non-empty lists of at most 1000 [beta, alpha, power] entries with alpha > 0 and power a list
    with one finite number per layer."""
    _output(runs, run)


@pytest.mark.parametrize('run', RUNS)
def test_mode_families(runs, run):
    """Requirement 3: for every guide, test frequency and direction, the families with at least one mode
    of attenuation <= 200 dB/m are exactly the true ones, with exactly the true number of modes each."""
    output = _output(runs, run)
    for what, rep, ref in _entries(output, run):
        assert set(rep) == set(ref), '%s: families %s reported, %s expected' % (what, sorted(rep), sorted(ref))
        for fam in ref:
            assert len(rep[fam]) == len(ref[fam]), '%s %s: %d modes reported, %d expected' % (
                what, fam, len(rep[fam]), len(ref[fam]))


@pytest.mark.parametrize('run', RUNS)
def test_propagation_constants(runs, run):
    """Requirement 4: in each family and direction the reported gamma = alpha + j beta pair one-to-one
    with the true values, each within |gamma - gamma*| <= 1e-7 |gamma*|."""
    output = _output(runs, run)
    for what, rep, ref in _entries(output, run):
        assert set(rep) == set(ref), '%s: families differ' % what
        for fam in ref:
            miss, extra, _ = _match(rep[fam], ref[fam])
            assert not miss and not extra, \
                '%s %s: no reported mode matches gamma* = %s; unmatched reported gamma %s' % (
                    what, fam, ['%.9g%+.9gj' % (z.real, z.imag) for z in miss],
                    ['%.9g%+.9gj' % (z.real, z.imag) for z in extra])


@pytest.mark.parametrize('run', RUNS)
def test_power_split(runs, run):
    """Requirement 5: for every matched mode, each reported layer fraction P_i / P of the time-averaged
    power flow is within 1e-6 sum_k |P_k* / P*| of the true fraction."""
    output = _output(runs, run)
    for what, rep, ref in _entries(output, run):
        assert set(rep) == set(ref), '%s: families differ' % what
        for fam in ref:
            miss, extra, pairs = _match(rep[fam], ref[fam])
            assert not miss and not extra, '%s %s: modes do not match' % (what, fam)
            for r, t in pairs:
                tp = [float(x) for x in t[2]]
                scale = sum(abs(x) for x in tp)
                bad = [i for i, (x, y) in enumerate(zip(r[2], tp)) if abs(x - y) > TOL_POWER * scale]
                assert not bad, '%s %s mode beta = %.6g: power fractions of layers %s are %s, expected %s' % (
                    what, fam, float(t[0]), bad, [r[2][i] for i in bad], ['%.9g' % tp[i] for i in bad])
