"""Verifier for /root/results/modes.json (loaded-waveguide-modes).

Only the agent's JSON file is read; it is parsed as data and never executed.
Reference values live in /tests/truth.json (generated by
/tests/truth_generator/make_truth.py from /tests/data/guides.json, which is
byte-identical to the agent's /root/data/guides.json).  Values are stored and
compared as gamma = alpha + j beta.
"""
import json
import math
import os
import re
import stat

import pytest

OUTPUT = '/root/results/modes.json'
GUIDES = '/tests/data/guides.json'
TRUTH = '/tests/truth.json'

MAX_BYTES = 16 * 1024 * 1024
MAX_FAMILIES = 400
MAX_LIST = 1000
KEYS = {'modes'}
DIRS = {'forward', 'reverse'}
FAMILY = re.compile(r'LSE(0|[1-9][0-9]*)|LSM[1-9][0-9]*')   # used with fullmatch

TOL_GAMMA = 1e-7          # |gamma - gamma*| <= TOL_GAMMA |gamma*|, gamma = alpha + j beta


# --------------------------------------------------------------- loading ---

def _reject_constant(name):
    raise ValueError('non-finite JSON constant %s' % name)


def _unique_keys(pairs):
    keys = [k for k, _ in pairs]
    if len(set(keys)) != len(keys):
        raise ValueError('repeated key in a JSON object')
    return dict(pairs)


def _read_output():
    """Read the artifact without following symlinks or blocking on FIFOs."""
    st = os.lstat(OUTPUT)
    if not stat.S_ISREG(st.st_mode):
        raise AssertionError('%s is not a regular file' % OUTPUT)
    if st.st_size > MAX_BYTES:
        raise AssertionError('%s is larger than 16 MiB' % OUTPUT)
    fd = os.open(OUTPUT, os.O_RDONLY | os.O_NONBLOCK | getattr(os, 'O_NOFOLLOW', 0))
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise AssertionError('%s is not a regular file' % OUTPUT)
        chunks = []
        total = 0
        while True:
            b = os.read(fd, 1 << 20)
            if not b:
                break
            total += len(b)
            if total > MAX_BYTES:
                raise AssertionError('%s is larger than 16 MiB' % OUTPUT)
            chunks.append(b)
    finally:
        os.close(fd)
    return json.loads(b''.join(chunks).decode('utf-8'), parse_constant=_reject_constant,
                      object_pairs_hook=_unique_keys)


def _is_number(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def _pair_ok(p):
    return isinstance(p, list) and len(p) == 2 and all(_is_number(x) for x in p) and p[1] > 0


def _check_family_map(obj, what):
    assert isinstance(obj, dict) and len(obj) <= MAX_FAMILIES, \
        '%s must be an object with at most %d families' % (what, MAX_FAMILIES)
    for fam, lst in obj.items():
        assert isinstance(fam, str) and FAMILY.fullmatch(fam), '%s: %r is not a family name' % (what, fam)
        assert isinstance(lst, list) and 1 <= len(lst) <= MAX_LIST and all(_pair_ok(x) for x in lst), \
            '%s[%s] must be a non-empty list of at most %d [beta, alpha] pairs of finite numbers with alpha > 0' % (
                what, fam, MAX_LIST)


def _check_contract(out, guides):
    """Raise AssertionError naming the first field that breaks the format."""
    assert isinstance(out, dict) and set(out) == {'guides'}, 'top level must be {"guides": ...}'
    res = out['guides']
    assert isinstance(res, dict), '"guides" must be an object'
    ids = {g['id'] for g in guides}
    assert set(res) == ids, 'guide ids differ from the input: missing %s, extra %s' % (
        sorted(ids - set(res)), sorted(set(res) - ids))
    for g in guides:
        gid = g['id']
        r = res[gid]
        assert isinstance(r, dict) and set(r) == KEYS, '%s: keys must be exactly %s' % (gid, sorted(KEYS))
        m = r['modes']
        assert isinstance(m, list) and len(m) == len(g['test_frequencies']), \
            '%s: modes must have one entry per test frequency' % gid
        for j, item in enumerate(m):
            assert isinstance(item, dict) and set(item) == DIRS, \
                '%s modes[%d] must be an object with exactly the keys forward and reverse' % (gid, j)
            for dr in ('forward', 'reverse'):
                _check_family_map(item[dr], '%s modes[%d].%s' % (gid, j, dr))


@pytest.fixture(scope='module')
def guides():
    with open(GUIDES) as fh:
        return json.load(fh)['guides']


@pytest.fixture(scope='module')
def truth():
    with open(TRUTH) as fh:
        return json.load(fh)


@pytest.fixture(scope='module')
def output(guides):
    out = _read_output()
    _check_contract(out, guides)
    return out['guides']


def _match(rep, ref):
    """Pair reported and true gamma values one-to-one within the tolerance.  The true values of one
    family are at least 1e-4 |gamma| apart (instruction), a thousand times the tolerance, so a
    reported value lies within the tolerance of at most one true value.  Returns the true values
    left unmatched and the reported values left unmatched."""
    left = [complex(a, b) for b, a in rep]
    miss = []
    for b, a in ref:
        g = complex(float(a), float(b))
        k = next((i for i, x in enumerate(left) if abs(x - g) <= TOL_GAMMA * abs(g)), None)
        if k is None:
            miss.append(g)
        else:
            left.pop(k)
    return miss, left


def _entries(output, truth, guides):
    """(label, reported family map, true family map) for every guide, test frequency and direction."""
    for g in guides:
        gid = g['id']
        for j, (rep, ref) in enumerate(zip(output[gid]['modes'], truth[gid]['modes'])):
            for dr in ('forward', 'reverse'):
                yield '%s at %s Hz, %s' % (gid, g['test_frequencies'][j], dr), rep[dr], ref[dr]


def test_output_contract(guides):
    """The artifact is a regular file of at most 16 MiB holding exactly the required JSON
    structure: no key repeated in any object, every guide id and no other, exactly the key modes,
    one entry per test frequency with exactly the keys forward and reverse, family names that are
    exactly LSE<n> (n >= 0) or LSM<n> (n >= 1) with no leading zeros, spaces or newlines, at most
    400 families per map, non-empty lists of at most 1000 [beta, alpha] pairs, alpha > 0, and
    finite numbers everywhere (NaN/Infinity rejected)."""
    out = _read_output()
    _check_contract(out, guides)


def test_mode_families(output, truth, guides):
    """For every test frequency and both directions, the families with at least one mode of
    attenuation <= 200 dB/m are exactly the true ones, with exactly the true number of modes each."""
    for what, rep, ref in _entries(output, truth, guides):
        assert set(rep) == set(ref), '%s: families %s reported, %s expected' % (what, sorted(rep), sorted(ref))
        for fam in ref:
            assert len(rep[fam]) == len(ref[fam]), '%s %s: %d modes reported, %d expected' % (
                what, fam, len(rep[fam]), len(ref[fam]))


def test_propagation_constants(output, truth, guides):
    """In each family and direction the reported gamma = alpha + j beta pair one-to-one with the
    true values, each within |gamma - gamma*| <= 1e-7 |gamma*|."""
    for what, rep, ref in _entries(output, truth, guides):
        assert set(rep) == set(ref), '%s: families differ' % what
        for fam in ref:
            miss, extra = _match(rep[fam], ref[fam])
            assert not miss and not extra, \
                '%s %s: no reported mode matches gamma* = %s; unmatched reported gamma %s' % (
                    what, fam, ['%.9g%+.9gj' % (z.real, z.imag) for z in miss],
                    ['%.9g%+.9gj' % (z.real, z.imag) for z in extra])
